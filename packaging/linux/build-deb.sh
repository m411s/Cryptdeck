#!/usr/bin/env bash
# Package a release build of Cryptdeck as a .deb (Debian, Ubuntu, Mint, …).
#
#   packaging/linux/build-deb.sh <cryptdeck-binary> <version> [output-dir]
#
# Needs dpkg-deb, which every Debian-based system (and GitHub's Ubuntu
# runners) has. The binary only links against the C library; the graphics
# and keyboard libraries are loaded at run time, so they are "Recommends".
set -euo pipefail

bin=$1
version=$2
out=${3:-dist}

root=$(cd "$(dirname "$0")/../.." && pwd)
here="$root/packaging/linux"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# Debian versions: a pre-release "0.3.0-rc.1" must sort before "0.3.0".
deb_version=${version/-/\~}

pkg="$work/cryptdeck_${deb_version}_amd64"
install -d "$pkg/DEBIAN" \
           "$pkg/usr/bin" \
           "$pkg/usr/share/applications" \
           "$pkg/usr/share/icons/hicolor/256x256/apps" \
           "$pkg/usr/share/doc/cryptdeck"

install -m 755 "$bin" "$pkg/usr/bin/cryptdeck"
install -m 644 "$here/cryptdeck.desktop" "$pkg/usr/share/applications/cryptdeck.desktop"
install -m 644 "$root/assets/cryptdeck.png" "$pkg/usr/share/icons/hicolor/256x256/apps/cryptdeck.png"

# Our licenses, plus the notices of the bundled crates (generated by
# cargo-about, see about.toml; the Release workflow always provides them).
doc="$pkg/usr/share/doc/cryptdeck"
install -m 644 "$root/LICENSE-MIT" "$root/LICENSE-APACHE" "$doc/"
if [ -f "$root/THIRD-PARTY-LICENSES.html" ]; then
    install -m 644 "$root/THIRD-PARTY-LICENSES.html" "$doc/"
else
    echo "warning: THIRD-PARTY-LICENSES.html missing, the .deb won't include it" >&2
fi
cat > "$doc/copyright" <<COPYRIGHT
Format: https://www.debian.org/doc/packaging-manuals/copyright-format/1.0/
Upstream-Name: Cryptdeck
Source: https://github.com/m411s/Cryptdeck

Files: *
Copyright: Cryptdeck contributors
License: MIT or Apache-2.0
 Either license applies, at your option. The full texts are in
 /usr/share/doc/cryptdeck/LICENSE-MIT and /usr/share/doc/cryptdeck/LICENSE-APACHE.
 The licenses of the bundled open-source crates are in
 /usr/share/doc/cryptdeck/THIRD-PARTY-LICENSES.html.
COPYRIGHT
chmod 644 "$doc/copyright"

# Don't inherit a group-writable umask into the package.
find "$pkg" -type d -exec chmod 755 {} +

size=$(du -sk --exclude=DEBIAN "$pkg" | cut -f1)
cat > "$pkg/DEBIAN/control" <<CONTROL
Package: cryptdeck
Version: $deb_version
Architecture: amd64
Maintainer: m411s <m411s@users.noreply.github.com>
Installed-Size: $size
Depends: libc6 (>= 2.35), libgcc-s1
Recommends: udisks2, libwayland-client0, libxkbcommon0, libx11-6, libvulkan1
Section: utils
Priority: optional
Homepage: https://github.com/m411s/Cryptdeck
Description: Desktop app to unlock and lock VeraCrypt volumes
 Cryptdeck is a small graphical app for VeraCrypt volumes. It uses the
 system's disk service (udisks2), so VeraCrypt itself doesn't need to be
 installed. It is an early prototype and is not affiliated with or
 endorsed by IDRIX or the VeraCrypt project.
CONTROL

mkdir -p "$out"
file="$out/cryptdeck_${deb_version}_amd64.deb"
dpkg-deb --root-owner-group --build "$pkg" "$file" >/dev/null
echo "Built $file"
